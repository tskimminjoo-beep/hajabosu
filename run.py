"""접수 원문을 일괄 처리해 하자대장 테이블(DB)에 저장한다.

처리하는 접수 두 가지
  1) 입력 폴더(data/접수함)의 txt 원문
  2) 접수 화면(intake.py)으로 DB 접수 테이블에 들어온 미처리 접수
     - 접수일은 발견일을 쓴다. 처리하면 접수 테이블의 처리상태가 처리완료가 된다.

사용: python run.py [입력폴더]

AI 정리(ai.py) → 번호·기한·보증 판정(rules.py) → 대장 16개 항목으로 기록(db.py).
원본(접수함, 공사정보)은 고치지 않는다.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

import ai
import db
import rules

ROOT = Path(__file__).resolve().parent
기본_입력 = ROOT / "data" / "접수함"


def _파일명_날짜(이름: str):
    """파일명에서 YYYYMMDD를 찾아 YYYY-MM-DD로. 없으면 None."""
    m = re.search(r"(20\d{2})(\d{2})(\d{2})", 이름)
    return f"{m.group(1)}-{m.group(2)}-{m.group(3)}" if m else None


def _합치기(*메모) -> str | None:
    글 = [m for m in 메모 if m]
    return " / ".join(글) if 글 else None


class 번호표:
    """접수번호를 원문 하나에 한 번만 붙이고, 다시 처리해도 바꾸지 않는다.

    이미 대장에 있는 원문(파일명 또는 DB접수-id)은 그 접수번호를 그대로 쓰고,
    새 원문은 그 접수일의 가장 큰 순번 다음 번호를 받는다.
    그래서 접수함 파일과 DB 접수가 같은 날짜여도 번호가 겹쳐 서로 덮어쓰지 않는다.
    """

    def __init__(self, 대장행들: list[dict]):
        self.기존 = {r["원문파일"]: r["접수번호"] for r in 대장행들}
        self.최대 = defaultdict(int)
        for r in 대장행들:
            m = re.fullmatch(r"HJ-(\d{8})-(\d+)", r["접수번호"])
            if m:
                self.최대[m.group(1)] = max(self.최대[m.group(1)], int(m.group(2)))

    def 번호(self, 원문파일: str, 접수일: str) -> str:
        if 원문파일 in self.기존:
            return self.기존[원문파일]
        날짜 = 접수일.replace("-", "")
        self.최대[날짜] += 1
        self.기존[원문파일] = rules.접수번호(접수일, self.최대[날짜])
        return self.기존[원문파일]


def 행_만들기(원문파일: str, 정리: dict, 접수일: str, 접수번호: str, 공사목록: list[dict]):
    """AI 정리 결과 1건 → 대장 1행. (행, 보증판정 결과)를 돌려준다."""
    판정 = rules.보증판정(접수일, 정리["위치"], 정리["공종"], 공사목록)
    확인필요 = 판정["보증판정"] == "확인필요" or 정리["확인필요사유"]
    행 = {
        "접수번호": 접수번호,
        "접수일": 접수일,
        "원문파일": 원문파일,
        "위치": 정리["위치"],
        "공종": 정리["공종"],
        "하자내용": 정리["하자내용"],
        "긴급도": 정리["긴급도"],
        "조치기한": rules.조치기한(접수일, 정리["긴급도"]).isoformat(),
        "공사번호": 판정["공사번호"],
        "시공업체": 판정["시공업체"],
        "준공일": 판정["준공일"],
        "보증만료일": 판정["보증만료일"],
        "보증판정": 판정["보증판정"],
        "책임구분": 판정["책임구분"],
        "상태": "확인필요" if 확인필요 else "판정완료",
        "비고": _합치기(판정["비고"], 정리["확인필요사유"]),
    }
    return 행, 판정


def _접수_원문(접수: dict) -> str:
    """DB 접수 1건을 AI에게 줄 원문 글로 만든다."""
    return (
        "[접수 화면 접수]\n"
        f"접수자: {접수['접수자']} ({접수['부서']})\n"
        f"발견일: {접수['발견일']}\n"
        f"위치: {접수['위치']}\n"
        f"내용: {접수['내용']}\n"
    )


def 처리_파일(입력폴더: Path, 표: 번호표, 공사목록: list[dict]) -> list[dict]:
    행들 = []
    for 파일 in sorted(입력폴더.glob("*.txt")):
        정리 = ai.접수정리(파일)

        # 접수일: 원문(AI) → 없으면 파일명 날짜 (업무설명 2)
        접수일 = 정리["접수일"] or _파일명_날짜(파일.name)
        if not 접수일:
            raise SystemExit(f"접수일을 알 수 없습니다: {파일.name}")

        행, _ = 행_만들기(파일.name, 정리, 접수일, 표.번호(파일.name, 접수일), 공사목록)
        행들.append(행)
        print(f"  {행['접수번호']}  {파일.name}  →  {행['보증판정']}")
    return 행들


def 처리_DB접수(표: 번호표, 공사목록: list[dict]) -> list[dict]:
    """접수 테이블의 미처리 접수를 대장으로 옮긴다. 접수일은 발견일.

    한 건이 실패해도 나머지는 계속하고, 실패한 건은 미처리로 남긴다.
    """
    처리된 = []  # (접수 id, 대장 행)
    for 접수 in db.접수_읽기("미처리"):
        이름 = f"DB접수-{접수['id']}"
        # 발견일이 비어 있으면 접수일시의 날짜를 쓴다.
        접수일 = 접수["발견일"] or 접수["접수일시"][:10]
        try:
            정리 = ai.접수정리_글(_접수_원문({**접수, "발견일": 접수일}), 이름)
            행, _ = 행_만들기(이름, 정리, 접수일, 표.번호(이름, 접수일), 공사목록)
        except Exception as e:
            print(f"  {이름}  →  실패({type(e).__name__}), 미처리로 남김")
            continue
        처리된.append((int(접수["id"]), 행))  # db.접수_읽기는 값을 문자열로 돌려준다
        print(f"  {행['접수번호']}  {이름}  →  {행['보증판정']}")

    # 대장에 먼저 저장하고, 그다음 접수를 처리완료로 바꾼다.
    # 중간에 멈춰도 다시 돌리면 같은 접수번호로 갈아 쓰므로 중복되지 않는다.
    db.대장_저장([행 for _, 행 in 처리된])
    for 접수_id, 행 in 처리된:
        db.접수_처리완료(접수_id, 행["접수번호"])
    return [행 for _, 행 in 처리된]


def 처리(입력폴더: Path) -> list[dict]:
    """접수함 파일 + DB 미처리 접수를 모두 처리해 하자대장 테이블에 저장한다."""
    공사목록 = rules.공사정보_읽기()
    표 = 번호표(db.대장_읽기())

    print("접수함 파일")
    파일행들 = 처리_파일(입력폴더, 표, 공사목록)
    # 저장은 db.py에서만 한다. 접수번호가 같으면 갈아 쓴다.
    db.대장_저장(파일행들)

    print("DB 접수")
    db행들 = 처리_DB접수(표, 공사목록)
    return 파일행들 + db행들


if __name__ == "__main__":
    입력 = Path(sys.argv[1]) if len(sys.argv) > 1 else 기본_입력
    print(f"처리 시작: {입력}")
    행들 = 처리(입력)
    print(f"{len(행들)}건 하자대장 테이블에 저장")
